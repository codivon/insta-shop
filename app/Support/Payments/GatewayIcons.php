<?php

namespace App\Support\Payments;

use App\Models\Setting;
use Illuminate\Support\Facades\Storage;

/**
 * v0.29.0 — per-gateway ICON resolution (client request: «همه درگاه‌های
 * پرداخت تصویر یا آیکون مخصوص داشته باشند و قابل تغییر باشند، پیش‌فرض هم
 * آیکون خود درگاه‌ها باشد — هم در قسمت مدیریت و هم در صفحه checkout»).
 *
 * Resolution order (partials/gateway-logo):
 *   1. CUSTOM upload — settings key payment.{gateway}.icon holds a
 *      relative path on the PUBLIC disk (gateway-icons/{gateway}.{ext},
 *      uploaded live from the admin panel, PNG/JPG/WebP only);
 *   2. BUNDLED brand tile — public/images/gateways/{gateway}.svg
 *      (generated by scripts/generate-gateway-icons.php, committed);
 *   3. (rendered inside the partial) the old gradient-letter fallback
 *      for a gateway key that has neither of the two.
 */
class GatewayIcons
{
    /** Public disk — the disk every public-facing upload already uses. */
    public const DISK = 'public';

    /** Directory the custom uploads live in (relative to the disk root). */
    public const STORAGE_DIR = 'gateway-icons';

    /** Bundled (repo-owned, trusted) default SVG tiles. */
    public const DEFAULT_DIR = 'images/gateways';

    /** Custom uploads NEVER accept SVG — an SVG on a web-served disk is an XSS vector; sanitize-by-refusal. */
    public const ALLOWED_EXTENSIONS = ['png', 'jpg', 'jpeg', 'webp'];

    public static function settingKey(string $gateway): string
    {
        return "payment.{$gateway}.icon";
    }

    /** The stored relative path of a gateway's custom icon, validated; null when absent. */
    public static function customPath(string $gateway): ?string
    {
        $path = (string) Setting::get(self::settingKey($gateway), '');

        if ($path === ''
            || ! str_starts_with($path, self::STORAGE_DIR.'/')
            || str_contains($path, '..')) {
            return null;
        }

        return $path;
    }

    /** Public URL of the custom icon (cache-busted with the file mtime) or null. */
    public static function customUrl(string $gateway): ?string
    {
        $path = self::customPath($gateway);

        if ($path === null || ! Storage::disk(self::DISK)->exists($path)) {
            return null;
        }

        $mtime = Storage::disk(self::DISK)->lastModified($path);

        return Storage::disk(self::DISK)->url($path).'?v='.$mtime;
    }

    /** Bundled default brand tile URL, or null when the slug has no SVG. */
    public static function defaultUrl(string $gateway): ?string
    {
        $file = public_path(self::DEFAULT_DIR."/{$gateway}.svg");

        return is_file($file) ? asset(self::DEFAULT_DIR."/{$gateway}.svg") : null;
    }

    public static function hasCustom(string $gateway): bool
    {
        return self::customPath($gateway) !== null;
    }

    /**
     * Persist an uploaded file as the gateway's custom icon: one file per
     * gateway (gateway-icons/{gateway}.{ext}) — any previous custom icon
     * (old extension included) is deleted first, so stale files never
     * accumulate on the public disk.
     */
    public static function store(string $gateway, string $extension, string $contents): string
    {
        self::deleteFiles($gateway);

        $path = self::STORAGE_DIR."/{$gateway}.".$extension;

        Storage::disk(self::DISK)->put($path, $contents);

        Setting::set(self::settingKey($gateway), $path);

        return $path;
    }

    /** Drop the custom icon (file + setting) → the gateway falls back to its bundled tile. */
    public static function deleteCustom(string $gateway): void
    {
        self::deleteFiles($gateway);

        Setting::forget(self::settingKey($gateway));
    }

    private static function deleteFiles(string $gateway): void
    {
        $disk = Storage::disk(self::DISK);

        // Exact stored path + every extension this gateway might have used before.
        $paths = [self::customPath($gateway)];

        foreach (self::ALLOWED_EXTENSIONS as $ext) {
            $paths[] = self::STORAGE_DIR."/{$gateway}.{$ext}";
        }

        foreach (array_filter(array_unique($paths)) as $path) {
            if ($disk->exists($path)) {
                $disk->delete($path);
            }
        }
    }
}
